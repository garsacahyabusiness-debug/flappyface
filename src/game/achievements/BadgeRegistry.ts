// Fix pure_wings shape to 'wings' cleanly below
export const FIXED_BADGE_REGISTRY: readonly BadgeDefinition[] = BADGE_REGISTRY.map((b) =>
  b.id === 'pure_wings' ? { ...b, shape: 'wings' as const } : b
);

export const BADGE_MAP: ReadonlyMap<string, BadgeDefinition> = new Map(
  FIXED_BADGE_REGISTRY.map((b) => [b.id, b])
);

export function getBadgeById(id: string | null | undefined): BadgeDefinition | null {
  if (!id) return null;
  return BADGE_MAP.get(id) ?? null;
}
