import { SkinId } from '../character/CharacterSkinManager';

interface Spec {
  id: string;
  name: string;
  description: string;
  category: AchievementCategory;
  rarity: AchievementRarity;
  requirement: number;
  icon: AchievementIconName;
  hidden?: boolean;
  secretHint?: string;
  requirementType?: AchievementRequirementType;
  badgeId?: string;
  titleId?: string;
  frameId?: AvatarFrameId;
  skinId?: SkinId;
  chainId?: string;
  chainOrder?: number;
  getValue?: (m: AchievementMetrics, unlockedCount?: number, unlockedHiddenCount?: number) => number;
}

function makeDef(s: Spec): AchievementDefinition {
  const preset = ACHIEVEMENT_RARITY_CONFIG[s.rarity];
  return {
    id: s.id,
    name: s.name,
    description: s.description,
    category: s.category,
    rarity: s.rarity,
    hidden: Boolean(s.hidden),
    secretHint: s.secretHint,
    requirement: s.requirement,
    requirementType: s.requirementType ?? 'custom',
    icon: s.icon,
    rewardCoins: preset.coins,
    rewardGems: preset.gems,
    rewardXP: preset.xp,
    points: preset.points,
    badgeId: s.badgeId,
    titleId: s.titleId,
    frameId: s.frameId,
    skinId: s.skinId,
    chainId: s.chainId,
    chainOrder: s.chainOrder,
    getValue: s.getValue
      ? (m) => s.getValue!(m)
      : undefined,
  };
}

