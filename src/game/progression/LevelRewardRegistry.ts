export const LEVEL_REWARD_MAP: ReadonlyMap<number, LevelRewardDef> = new Map(
  LEVEL_REWARD_TRACK.map((r) => [r.level, r])
);

export function getNextLevelReward(currentLevel: number, claimedLevels: readonly number[]): LevelRewardDef | null {
  // First check if there is an unclaimed reward already reached
  for (const r of LEVEL_REWARD_TRACK) {
    if (r.level <= currentLevel && !claimedLevels.includes(r.level)) {
      return r;
    }
  }
  // Otherwise return the next upcoming reward level
  for (const r of LEVEL_REWARD_TRACK) {
    if (r.level > currentLevel) {
      return r;
    }
  }
  return null;
}
